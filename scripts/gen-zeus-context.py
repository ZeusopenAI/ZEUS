#!/usr/bin/env python3
"""Sinh skill `zeus-context` từ trạng thái repo ZEUS.

Đây là "bộ nhớ ngoài" của Hermes: mỗi lần đồng bộ, skill này được viết lại để
Hermes biết dự án đang ở đâu, việc gì đang mở, quy tắc nào phải theo.

Nguyên tắc:
  - **Tất định**: cùng một commit → cùng một file (không chèn timestamp),
    nhờ vậy sync không tạo thay đổi giả mỗi lần chạy.
  - **Không cắt cụt giữa chừng**: mỗi mục có ngân sách ký tự riêng, cắt ở
    ranh giới dòng và ghi rõ "đọc đầy đủ tại <path>".
  - **Ưu tiên đúng thứ tự**: Status > TODO > AGENTS (quy tắc an toàn) > Roadmap.

Dùng:
    python3 scripts/gen-zeus-context.py --repo . --out /tmp/SKILL.md
    python3 scripts/gen-zeus-context.py --repo . --stdout --max-chars 20000
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

DEFAULT_MAX = 16000
MIN_SECTION = 300  # dưới mức này thì chỉ để con trỏ, không cố nhồi nội dung

SKILL_DESC_MAX = 160

TOP_DIR_PURPOSE = {
    "agents": "Runtime Hermes (vendored) + app desktop/installer",
    "skills": "Skill dùng lại cho Hermes (nguồn sự thật)",
    "docs": "Tài liệu vận hành, runbook, hướng dẫn",
    "deploy": "Script/systemd triển khai VPS",
    "scripts": "Script vận hành: sync, validate, kiểm tra",
    "flowkit": "Ứng dụng AI filmmaking độc lập",
    "site": "Landing page tĩnh (GitHub Pages)",
    "memory": "Ghi chú bộ nhớ dài hạn của dự án",
    "colab": "Notebook chạy trên Google Colab",
    "android-keyboard": "Bàn phím Android",
    "worker": "Worker chạy nền",
    ".github": "CI/CD: workflows, template",
}


def sh(args: list[str], cwd: Path) -> str:
    try:
        return subprocess.run(
            args, cwd=cwd, capture_output=True, text=True, timeout=20, check=False
        ).stdout.strip()
    except Exception:
        return ""


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, text
    data: dict[str, str] = {}
    key = None
    buf: list[str] = []
    for raw in lines[1:end]:
        if raw[:1] in (" ", "\t") and key is not None:
            buf.append(raw.strip())
            continue
        if key is not None:
            data[key] = " ".join(buf).strip()
            key, buf = None, []
        if not raw.strip() or raw.lstrip().startswith("#") or ":" not in raw:
            continue
        k, _, v = raw.partition(":")
        v = v.strip()
        if v in ("|", ">", "|-", ">-", "|+", ">+"):
            key = k.strip()
        else:
            data[k.strip()] = v.strip("'\"")
    if key is not None:
        data[key] = " ".join(buf).strip()
    return data, "\n".join(lines[end + 1 :])


def first_heading(text: str) -> str:
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("#"):
            return line.lstrip("# ").strip()
        if line and not line.startswith(">"):
            return line
    return ""


def demote_headings(text: str, levels: int = 2) -> str:
    """Hạ cấp heading khi nhúng tài liệu khác vào, để mục lục của skill phẳng."""
    out = []
    in_code = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        if not in_code and line.startswith("#"):
            line = "#" * min(6, len(line) - len(line.lstrip("#")) + levels) + line.lstrip("#")
        out.append(line)
    return "\n".join(out)


def truncate_line_safe(text: str, limit: int, note: str) -> str:
    """Cắt ở ranh giới dòng, không chặt đôi ký tự UTF-8."""
    if len(text) <= limit:
        return text
    head = text[:limit]
    cut = head.rfind("\n")
    if cut > limit // 2:
        head = head[:cut]
    return head.rstrip() + f"\n\n_(cắt bớt để tiết kiệm context — đọc đầy đủ tại `{note}`)_\n"


def build(repo: Path, max_chars: int) -> str:
    git_sha = sh(["git", "rev-parse", "--short", "HEAD"], repo) or "unknown"
    git_full = sh(["git", "rev-parse", "--abbrev-ref", "HEAD"], repo) or "unknown"
    git_date = sh(["git", "log", "-1", "--format=%cs"], repo) or "unknown"

    out: list[str] = []
    out.append(
        "---\n"
        "name: zeus-context\n"
        "description: >-\n"
        "  AUTO-GENERATED snapshot of the ZEUS / Quang Quy AI repository: current\n"
        "  status, open work, roadmap, collaboration and safety rules, repo map, and\n"
        "  every available skill and doc. Load this before planning or acting on the\n"
        "  project so you never work from stale assumptions.\n"
        "license: MIT-compatible synthesized workflow; generated by scripts/gen-zeus-context.py.\n"
        "---\n\n"
        "# ZEUS Context (tự động sinh)\n\n"
        "> ⚠️ File này do `scripts/gen-zeus-context.py` sinh lại ở mỗi lần đồng bộ.\n"
        "> **Đừng sửa tay** — mọi thay đổi sẽ bị ghi đè. Muốn đổi nội dung thì sửa\n"
        "> `Status.md`, `TODO.md`, `Roadmap.md`, `AGENTS.md` trong repo rồi chạy lại sync.\n\n"
    )

    out.append("## Điểm neo\n\n")
    out.append(f"- Repo: `ZeusopenAI/ZEUS`\n")
    out.append(f"- Bản sao trên máy này: `{repo}`\n")
    out.append(f"- Nhánh: `{git_full}` · Commit: `{git_sha}` (commit gần nhất {git_date})\n")
    out.append("- Có thể đọc trực tiếp file trong bản sao trên (dùng tool terminal/file),\n")
    out.append("  snapshot này chỉ là bản tóm tắt để định hướng.\n\n")

    # ── Skill index ────────────────────────────────────────────────────────
    out.append("## Skill đang có (gọi bằng `/tên-skill` hoặc skill_view)\n\n")
    skills_dir = repo / "skills"
    skill_entries: list[str] = []
    if skills_dir.is_dir():
        for skill_md in sorted(skills_dir.glob("*/SKILL.md")):
            fm, _ = parse_frontmatter(skill_md.read_text(encoding="utf-8", errors="replace"))
            name = fm.get("name") or skill_md.parent.name
            desc = " ".join(fm.get("description", "").split())
            if len(desc) > SKILL_DESC_MAX:
                desc = desc[:SKILL_DESC_MAX].rsplit(" ", 1)[0] + "…"
            skill_entries.append(f"- `{name}` — {desc}" if desc else f"- `{name}`")
    out.append("\n".join(skill_entries) or "_(chưa có skill)_")
    out.append("\n\n")

    # ── Repo map ──────────────────────────────────────────────────────────
    out.append("## Bản đồ repo\n\n")
    for path in sorted(repo.iterdir()):
        if not path.is_dir() or path.name.startswith(".") and path.name != ".github":
            continue
        purpose = TOP_DIR_PURPOSE.get(path.name, "")
        if not purpose:
            readme = path / "README.md"
            purpose = first_heading(readme.read_text(encoding="utf-8", errors="replace")) if readme.is_file() else ""
        out.append(f"- `{path.name}/`" + (f" — {purpose}" if purpose else "") + "\n")
    out.append("\n")

    # ── Docs ──────────────────────────────────────────────────────────────
    out.append("## Tài liệu vận hành\n\n")
    docs_dir = repo / "docs"
    if docs_dir.is_dir():
        for doc in sorted(docs_dir.glob("*.md")):
            title = first_heading(doc.read_text(encoding="utf-8", errors="replace"))
            name = doc.name
            out.append(f"- `docs/{name}`" + (f" — {title}" if title else "") + "\n")
    out.append("\n")

    # ── Phần nội dung, ưu tiên theo thứ tự an toàn ────────────────────────
    footer = (
        "## Cách dùng snapshot này\n\n"
        "1. Đọc **Trạng thái** và **Việc đang mở** trước khi lập kế hoạch.\n"
        "2. Snapshot có thể cũ hơn code: kiểm tra `git log -1` trong bản sao repo trước khi khẳng định.\n"
        "3. Mục \"Tác vụ phải hỏi trước\" trong `AGENTS.md` là ràng buộc — không tự vượt qua.\n"
        "4. Hermes là kênh TÙY CHỌN: có thể gọi hoặc không gọi; thiếu/lỗi gợi ý Hermes KHÔNG\n"
        "   được dùng để dừng phiên hay từ chối yêu cầu của Operator (AGENTS.md ĐIỀU 0).\n"
        "5. Cần chi tiết hơn: đọc thẳng file trong repo (đường dẫn ở mục Bản đồ repo).\n"
    )
    fixed_len = sum(len(s) for s in out)
    sections = [
        ("Trạng thái hiện tại", "Status.md"),
        ("Việc đang mở", "TODO.md"),
        ("Quy tắc phối hợp & an toàn (BẮT BUỘC đọc — Hermes chỉ là tùy chọn)", "AGENTS.md"),
        ("Định hướng", "Roadmap.md"),
    ]
    pending = [(title, repo / name, name) for title, name in sections if (repo / name).is_file()]

    # Trừ hao 8% cho heading/mục lục chèn thêm, để file cuối không vượt quá cap.
    budget = int(max_chars * 0.92)
    remaining = budget - fixed_len - len(footer) - 200
    for idx, (title, path, name) in enumerate(pending):
        body = path.read_text(encoding="utf-8", errors="replace").strip()
        sections_left = len(pending) - idx
        # Chia đều phần còn lại, nhưng mục đầu (Status) được ưu tiên hơn.
        share = max(MIN_SECTION, remaining // max(1, sections_left)) - 150
        if remaining <= MIN_SECTION:
            out.append(f"## {title}\n\n_(Không nhồi vào snapshot để tiết kiệm context — đọc đầy đủ tại `{path}`)_\n\n")
            continue
        chunk = demote_headings(truncate_line_safe(body, share, path))
        out.append(f"## {title} (`{name}`)\n\n{chunk.strip()}\n\n")
        remaining = budget - sum(len(s) for s in out) - len(footer) - 200

    out.append(footer)

    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="Sinh skill zeus-context")
    ap.add_argument("--repo", default=".", help="thư mục repo ZEUS")
    ap.add_argument("--out", help="file đầu ra (mặc định: in ra stdout)")
    ap.add_argument("--stdout", action="store_true", help="in ra stdout dù có --out")
    ap.add_argument("--max-chars", type=int, default=DEFAULT_MAX)
    args = ap.parse_args()

    repo = Path(args.repo).resolve()
    if not (repo / "skills").is_dir():
        print(f"LỖI: {repo} không giống repo ZEUS (thiếu skills/)", file=sys.stderr)
        return 1

    content = build(repo, args.max_chars)

    if args.out and not args.stdout:
        Path(args.out).write_text(content, encoding="utf-8")
    else:
        sys.stdout.write(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
